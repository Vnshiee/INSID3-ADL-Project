"""Collect every metrics.json under an output root into Markdown + CSV tables.

Fold-averaged rows are only marked complete if every expected fold finished all
episodes; incomplete runs are listed with a warning, never silently averaged.

    python scripts/aggregate_results.py --root $INSID3_OUTPUT_ROOT --out results/summary
"""
import argparse
import csv
import glob
import json
import os
from collections import defaultdict

import _bootstrap  # noqa: F401

from insid3_ext.config import DATASET_FOLDS


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", required=True)
    ap.add_argument("--out", default="results/summary")
    args = ap.parse_args()

    files = sorted(glob.glob(os.path.join(args.root, "**", "metrics.json"), recursive=True))
    seg, corr = [], []
    for f in files:
        with open(f) as fp:
            m = json.load(fp)
        m["path"] = os.path.relpath(os.path.dirname(f), args.root)
        (corr if m.get("task") == "correspondence" else seg).append(m)

    os.makedirs(os.path.dirname(os.path.abspath(args.out)) or ".", exist_ok=True)
    lines = ["# Aggregated results (generated by scripts/aggregate_results.py)", "",
             f"Source: `{args.root}` — {len(files)} metrics files.", ""]

    # ---- segmentation: per run ----
    if seg:
        with open(args.out + "_segmentation_runs.csv", "w", newline="") as fp:
            keys = ["exp_name", "dataset", "split", "fold", "shots", "seed", "miou", "fbiou",
                    "n_episodes", "n_expected", "complete", "time_ms_mean", "peak_mem_mb_max", "path"]
            w = csv.DictWriter(fp, fieldnames=keys, extrasaction="ignore")
            w.writeheader()
            w.writerows(seg)
        groups = defaultdict(list)
        for m in seg:
            groups[(m["exp_name"], m["dataset"], m["split"], m["shots"], m["seed"])].append(m)
        lines += ["## Segmentation (mIoU %, mean over folds)", "",
                  "| experiment | dataset | split | shots | folds done | mIoU | per-fold | ms/episode | peak MB | status |",
                  "|---|---|---|---|---|---|---|---|---|---|"]
        for (exp, ds, split, shots, seed), runs in sorted(groups.items()):
            runs = sorted(runs, key=lambda r: r["fold"])
            expected = DATASET_FOLDS.get(ds, 1) if split == "test" else 1
            complete = len(runs) == expected and all(r["complete"] for r in runs)
            miou = sum(r["miou"] for r in runs) / len(runs)
            per = ", ".join(f"{r['miou']:.1f}" for r in runs)
            t = [r["time_ms_mean"] for r in runs if r.get("time_ms_mean")]
            mem = [r["peak_mem_mb_max"] for r in runs if r.get("peak_mem_mb_max")]
            lines.append(f"| {exp} | {ds} | {split} | {shots} | {len(runs)}/{expected} | {miou:.2f} | {per} | "
                         f"{(sum(t) / len(t)) if t else float('nan'):.0f} | {max(mem) if mem else float('nan'):.0f} | "
                         f"{'complete' if complete else 'INCOMPLETE'} |")
        lines.append("")

    # ---- correspondence ----
    if corr:
        lines += ["## Semantic correspondence (SPair-71k, PCK %)", "",
                  "| experiment | model | px | s | debiased | mode | PCK@0.05 | @0.10 | @0.15 | @0.20 | pairs | status |",
                  "|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for m in sorted(corr, key=lambda r: r["exp_name"]):
            lines.append(f"| {m['exp_name']} | {m['model_size']} | {m['image_size']} | {m['svd_components']} | "
                         f"{m['debiased']} | {m['debias_mode']} | {m['pck@0.05']:.2f} | {m['pck@0.1']:.2f} | "
                         f"{m['pck@0.15']:.2f} | {m['pck@0.2']:.2f} | {m['n_pairs']}/{m['n_expected']} | "
                         f"{'complete' if m['complete'] else 'INCOMPLETE'} |")
        lines.append("")

    with open(args.out + ".md", "w") as fp:
        fp.write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()

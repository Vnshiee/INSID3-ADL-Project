"""Model selection on the COCO *tuning* split only (never on test episodes).

Reads every complete run under <output_root>/*/coco-tune/, ranks Task-1 runs
(exp_name starting with 't1_'), Task-2 runs ('t2_') and combined runs ('c_'), and writes
    configs/selected/task1.yaml     best Task-1 debias section
    configs/selected/task2.yaml     best Task-2 prototypes section (+ its merge threshold)
    configs/selected/combined.yaml  best Task-1 debias + best Task-2 prototypes
    configs/selected/selection_report.md
The baseline tune score is reported for reference. Ties are broken by the earlier name.

    python scripts/select_best.py --root $INSID3_OUTPUT_ROOT
"""
import argparse
import glob
import json
import os

import _bootstrap  # noqa: F401
import yaml

from _bootstrap import ROOT


def _runs(root):
    out = []
    for f in glob.glob(os.path.join(root, "*", "coco-tune", "*", "metrics.json")):
        with open(f) as fp:
            m = json.load(fp)
        if not m.get("complete"):
            print(f"[skip incomplete] {f}")
            continue
        with open(os.path.join(os.path.dirname(f), "config.yaml")) as fp:
            m["config"] = yaml.safe_load(fp)
        out.append(m)
    return out


def _best(runs, prefix):
    cand = sorted((r for r in runs if r["exp_name"].startswith(prefix)), key=lambda r: (-r["miou"], r["exp_name"]))
    return cand


def _write(path, data, comment):
    with open(path, "w") as fp:
        fp.write(f"# AUTO-GENERATED by scripts/select_best.py — {comment}\n")
        yaml.safe_dump(data, fp, sort_keys=False)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", required=True)
    ap.add_argument("--out-dir", default=os.path.join(ROOT, "configs", "selected"))
    args = ap.parse_args()
    runs = _runs(args.root)
    if not runs:
        raise SystemExit("No complete tuning runs found (run run_task1.sh / run_task2.sh with STAGE=tune).")
    os.makedirs(args.out_dir, exist_ok=True)
    base = [r for r in runs if r["exp_name"] == "baseline"]
    t1, t2 = _best(runs, "t1_"), _best(runs, "t2_")
    rep = ["# Selection report (COCO train2014 tuning episodes; test sets untouched)", ""]
    if base:
        rep.append(f"Baseline tune mIoU: {base[0]['miou']:.2f}\n")
    for name, lst in (("Task 1", t1), ("Task 2", t2), ("Combined", _best(runs, "c_"))):
        rep += [f"## {name}", "", "| rank | exp | mIoU |", "|---|---|---|"]
        rep += [f"| {i + 1} | {r['exp_name']} | {r['miou']:.2f} |" for i, r in enumerate(lst)]
        rep.append("")

    base_rel = os.path.relpath(os.path.join(ROOT, "configs", "base.yaml"), args.out_dir)
    if t1:
        _write(os.path.join(args.out_dir, "task1.yaml"),
               {"_base_": base_rel, "debias": t1[0]["config"]["debias"], "run": {"exp_name": "sel_task1"}},
               f"best Task-1 tune run: {t1[0]['exp_name']} ({t1[0]['miou']:.2f})")
    if t2:
        _write(os.path.join(args.out_dir, "task2.yaml"),
               {"_base_": base_rel, "prototypes": t2[0]["config"]["prototypes"],
                "model": {"merge_threshold": t2[0]["config"]["model"]["merge_threshold"]},
                "run": {"exp_name": "sel_task2"}},
               f"best Task-2 tune run: {t2[0]['exp_name']} ({t2[0]['miou']:.2f})")
    if t1 and t2:
        _write(os.path.join(args.out_dir, "combined.yaml"),
               {"_base_": base_rel, "debias": t1[0]["config"]["debias"],
                "prototypes": t2[0]["config"]["prototypes"],
                "model": {"merge_threshold": t2[0]["config"]["model"]["merge_threshold"]},
                "run": {"exp_name": "sel_combined"}},
               f"{t1[0]['exp_name']} + {t2[0]['exp_name']}")
    with open(os.path.join(args.out_dir, "selection_report.md"), "w") as fp:
        fp.write("\n".join(rep) + "\n")
    print("\n".join(rep))
    print(f"wrote selected configs to {args.out_dir}")


if __name__ == "__main__":
    main()

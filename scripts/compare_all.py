"""Paired comparison of every experiment against a reference experiment (default: baseline).

For each (experiment, dataset, split, shots, seed) that has the same set of folds as the
reference, runs the fold-stratified paired bootstrap of compare_runs.py and writes
<out>.json and a Markdown table <out>.md.

    python scripts/compare_all.py --root $INSID3_OUTPUT_ROOT --reference baseline --out results/comparisons
"""
import argparse
import glob
import json
import os
from collections import defaultdict

import _bootstrap  # noqa: F401

from compare_runs import compare_segmentation


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", required=True)
    ap.add_argument("--reference", default="baseline")
    ap.add_argument("--out", default="results/comparisons")
    ap.add_argument("--bootstrap", type=int, default=5000)
    args = ap.parse_args()

    runs = defaultdict(dict)   # (exp, dataset_dir, shots, seed) -> {fold: dir}
    for f in glob.glob(os.path.join(args.root, "*", "*", "fold*_shot*_seed*", "metrics.json")):
        d = os.path.dirname(f)
        with open(f) as fp:
            m = json.load(fp)
        if m.get("task") != "segmentation" or not m.get("complete"):
            continue
        ds_dir = os.path.basename(os.path.dirname(d))
        runs[(m["exp_name"], ds_dir, m["shots"], m["seed"])][m["fold"]] = d

    results = []
    for (exp, ds, shots, seed), folds in sorted(runs.items()):
        if exp == args.reference:
            continue
        ref = runs.get((args.reference, ds, shots, seed))
        if not ref or set(ref) != set(folds):
            continue
        fs = sorted(folds)
        res = compare_segmentation([ref[f] for f in fs], [folds[f] for f in fs], args.bootstrap, 0)
        res.update(exp=exp, dataset=ds, shots=shots, seed=seed, folds=fs)
        results.append(res)

    os.makedirs(os.path.dirname(os.path.abspath(args.out)) or ".", exist_ok=True)
    with open(args.out + ".json", "w") as fp:
        json.dump(results, fp, indent=2)
    lines = [f"# Paired bootstrap vs `{args.reference}` (generated by scripts/compare_all.py)", "",
             "| experiment | dataset | shots | folds | ref mIoU | mIoU | Δ | 95% CI | p |", "|---|---|---|---|---|---|---|---|---|"]
    for r in results:
        lines.append(f"| {r['exp']} | {r['dataset']} | {r['shots']} | {len(r['folds'])} | {r['miou_a']:.2f} | "
                     f"{r['miou_b']:.2f} | {r['delta']:+.2f} | [{r['ci95'][0]:+.2f}, {r['ci95'][1]:+.2f}] | "
                     f"{r['p_two_sided']:.3f} |")
    with open(args.out + ".md", "w") as fp:
        fp.write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
